/**
 * AI 답변에서 마크다운 기호를 걷어낸다. 화면은 일반 텍스트로 보여 주므로
 * **굵게** 는 '따옴표' 로, 코드 울타리(```)와 머리글(#)은 지우고 내용만 남긴다.
 */
export function plainText(s: string): string {
  return (
    s
      // ```lang ... ``` → 내용만
      .replace(/```[a-zA-Z0-9_-]*\n?([\s\S]*?)```/g, (_m, body: string) => body.replace(/\n$/, ""))
      // **굵게** / __굵게__ → '굵게'
      .replace(/\*\*(.+?)\*\*/g, "'$1'")
      .replace(/__(.+?)__/g, "'$1'")
      // 줄 맨 앞 머리글 기호
      .replace(/^#{1,6}\s+/gm, "")
      // 남은 홑별표 강조 *기울임* → 그대로 글자만
      .replace(/(^|[\s(])\*(?!\s)([^*\n]+?)\*(?=[\s).,!?]|$)/g, "$1$2")
      .trim()
  );
}
